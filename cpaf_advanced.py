from cpaf.reproducibility import require_fresh_output_dir, require_outputs_absent

APPS = ["Paytm", "Google Pay", "PhonePe"]
DIMENSIONS = [
    "Data Minimisation", "Consent & Transparency", "Third-Party Sharing",
    "Security Controls", "Anonymisation & Re-identification",
    "Data Lifecycle & User Rights", "DPDP Alignment"
]
# Layer 1: dimension weights. These are initial research weights, not legal truth.
WEIGHTS = {
    "Data Minimisation": 1.2, "Consent & Transparency": 1.3,
    "Third-Party Sharing": 1.2, "Security Controls": 1.2,
    "Anonymisation & Re-identification": 1.0,
    "Data Lifecycle & User Rights": 1.1, "DPDP Alignment": 1.0
}
OUT = Path("cpaf_outputs")

def validate_score(score):
    return score is not None and 1 <= float(score) <= 5

def format_evidence_for_display(evidence):
    """Return a display copy with missing text fields blank, without inventing evidence."""
    display = evidence.copy()
    text_columns = (
        "claim", "source_title", "source_url", "access_date", "source_type",
        "evidence_note", "reviewer", "review_status", "score_rationale", "notes",
    )
    for column in text_columns:
        if column in display.columns:
            display[column] = display[column].where(display[column].notna(), "")
    for column in ("evidence_strength", "raw_score"):
        if column in display.columns:
            display[column] = display[column].astype(object).where(display[column].notna(), "")
    return display

def validate_evidence_rows(evidence):
    """Return per-row eligibility and missing requirements without changing evidence."""
    requirements = ("review_status", "source_url", "access_date", "claim", "reviewer",
                   "score_rationale", "raw_score")
    eligible = pd.Series(False, index=evidence.index, dtype=bool)
    issues = []
    numeric_scores = (pd.to_numeric(evidence["raw_score"], errors="coerce")
                      if "raw_score" in evidence else pd.Series(np.nan, index=evidence.index))
    for position, (_, row) in enumerate(evidence.iterrows()):
        missing = [column for column in requirements if column not in evidence.columns]
        if "review_status" in evidence.columns and str(row.get("review_status", "")).strip().lower() != "reviewed":
            missing.append("review_status=reviewed")
        for column in ("access_date", "claim", "reviewer", "score_rationale"):
            value = row.get(column)
            if column in evidence.columns and (pd.isna(value) or not str(value).strip()):
                missing.append(column)
        source = row.get("source_url")
        try:
            parsed = urlparse(str(source).strip()) if pd.notna(source) else None
            valid_source = parsed is not None and parsed.scheme in {"http", "https"} and bool(parsed.netloc)
        except (TypeError, ValueError):
            valid_source = False
        if "source_url" in evidence.columns and not valid_source:
            missing.append("valid HTTP(S) source_url")
        score = numeric_scores.iloc[position]
        if pd.isna(score) or not 1 <= float(score) <= 5:
            missing.append("raw_score (1–5)")
        strength = row.get("evidence_strength")
        try:
            numeric_strength = float(strength)
            valid_strength = np.isfinite(numeric_strength) and 0 <= numeric_strength <= 1
        except (TypeError, ValueError):
            valid_strength = False
        if not valid_strength:
            missing.append("evidence_strength (0–1)")
        row_issues = list(dict.fromkeys(missing))
        issues.append(row_issues)
        eligible.iloc[position] = not row_issues
    return eligible, issues

def evidence_adjusted_score(raw_score, evidence_strength):
    """Layer 2: evidence strength discounts unsupported certainty, without asserting a bad practice."""
    if not validate_score(raw_score):
        return np.nan
    # Evidence strength is 0..1: primary/current evidence gets more weight than vague statements.
    # Shrink weakly supported scores toward neutral 3.
    return round(3 + (float(raw_score) - 3) * float(evidence_strength), 3)

def compute_app_metrics(evidence):
    """
    Evidence CSV columns:
    app,dimension,raw_score,evidence_strength,source_type,source_url,access_date,notes
    raw_score: 1..5; evidence_strength: 0..1.
    """
    rows = []
    for app in APPS:
        app_rows = evidence[evidence["app"] == app]
        dim_scores = {}
        evidence_coverage = 0
        for dim in DIMENSIONS:
            d = app_rows[app_rows["dimension"] == dim]
            if d.empty:
                dim_scores[dim] = np.nan
                continue
            # Do not turn an unsupported assumption into an app score. Evidence must
            # meet the shared row eligibility checks before scoring.
            eligible, _ = validate_evidence_rows(d)
            d = d.loc[eligible]
            if d.empty:
                dim_scores[dim] = np.nan
                continue
            valid = d[pd.to_numeric(d["raw_score"], errors="coerce").between(1,5)].copy()
            if valid.empty:
                dim_scores[dim] = np.nan
                continue
            valid["evidence_strength"] = pd.to_numeric(valid["evidence_strength"], errors="coerce").fillna(0).clip(0,1)
            adjusted = [evidence_adjusted_score(s, e) for s,e in zip(valid["raw_score"], valid["evidence_strength"])]
            # Multiple pieces of evidence: weighted average by evidence strength.
            weights = valid["evidence_strength"].to_numpy()
            dim_scores[dim] = round(float(np.average(adjusted, weights=weights)) if weights.sum() else 3.0, 3)
            evidence_coverage += 1
        available = [(dim_scores[d], WEIGHTS[d]) for d in DIMENSIONS if not np.isnan(dim_scores[d])]
        weighted_cpi = sum(s*w for s,w in available) / sum(w for _,w in available) if available else np.nan
        coverage = evidence_coverage / len(DIMENSIONS)
        # Layer 3: confidence reflects coverage and average evidence strength.
        strengths = pd.to_numeric(app_rows.get("evidence_strength", pd.Series(dtype=float)), errors="coerce").dropna()
        mean_strength = float(strengths.clip(0,1).mean()) if len(strengths) else 0
        confidence = round(100 * coverage * mean_strength, 1)
        rows.append({"App":app, **dim_scores, "Weighted CPI":round(weighted_cpi,3) if not np.isnan(weighted_cpi) else np.nan,
                     "Evidence coverage (%)":round(coverage*100,1), "Evidence confidence (%)":confidence})
    return pd.DataFrame(rows)

def compute_weight_sensitivity(metrics):
    """Compare primary, equal and reverse-priority weights on dimensions with evidence."""
    output=[]
    for _, row in metrics.iterrows():
        available=[d for d in DIMENSIONS if pd.notna(row[d])]
        choices={"primary":{d:WEIGHTS[d] for d in available},
                 "equal":{d:1.0 for d in available},
                 "reverse_priority":{d:1.0/WEIGHTS[d] for d in available}}
        item={"App":row["App"]}
        for name, weights in choices.items():
            total=sum(weights.values())
            item[name+"_weighted_cpi"]=(sum(float(row[d])*weights[d] for d in available)/total) if total else np.nan
        output.append(item)
    return pd.DataFrame(output)

def make_synthetic_transactions(n=50000, seed=42):
    """Create a synthetic dataset for testing privacy transformations; no real user data."""
    return generate_synthetic(n, seed)

def generalise(df):
    return generalize(df)

def enforce_k_anonymity(df, quasi, k=5):
    """Simple suppression of equivalence classes smaller than k; demonstration, not production-grade anonymisation."""
    return suppress_k(df, quasi, k)[0]

def privacy_metrics(original, transformed, quasi, sensitive="risk_category"):
    if transformed.empty:
        return {"records_retained_pct":0.0,"min_group_size":0,"k_anonymity":0,
                "min_distinct_sensitive":0,"mean_tv_distance":np.nan}
    sizes = transformed.groupby(quasi, dropna=False).size()
    diversity = transformed.groupby(quasi, dropna=False)[sensitive].nunique()
    overall = transformed[sensitive].value_counts(normalize=True)
    tvs = []
    for _, grp in transformed.groupby(quasi, dropna=False):
        local = grp[sensitive].value_counts(normalize=True)
        idx = overall.index.union(local.index)
        tvs.append(float((overall.reindex(idx, fill_value=0)-local.reindex(idx, fill_value=0)).abs().sum()/2))
    return {
        "records_retained_pct":round(100*len(transformed)/max(len(original),1),2),
        "min_group_size":int(sizes.min()),
        "k_anonymity":int(sizes.min()),
        "min_distinct_sensitive":int(diversity.min()),
        "mean_tv_distance":round(float(np.mean(tvs)),4)
    }

def run_privacy_lab(n=50000, k=5, seed=42, l=2, t=.2):
    output_files=("synthetic_transactions.csv", "generalised_synthetic_data.csv",
                  "k_anonymous_synthetic_data.csv", "privacy_lab_metrics.csv",
                  "privacy_diagnostics.csv", "experiment_manifest.json")
    require_outputs_absent(OUT, output_files)
    raw = make_synthetic_transactions(n, seed)
    transformed = generalise(raw)
    quasi = ["age_band","location","merchant_type","amount_band","time_band"]
    anon = enforce_k_anonymity(transformed, quasi, k)
    metrics_before = privacy_metrics(raw, transformed, quasi)
    metrics_after = privacy_metrics(raw, anon, quasi)
    quality = validate_dataset(raw)
    OUT.mkdir(parents=True, exist_ok=True)
    raw.to_csv(OUT/"synthetic_transactions.csv", index=False)
    transformed.to_csv(OUT/"generalised_synthetic_data.csv", index=False)
    anon.to_csv(OUT/"k_anonymous_synthetic_data.csv", index=False)
    pd.DataFrame([
        {"stage":"Generalisation only", **metrics_before},
        {f"stage":f"Generalisation + k-suppression (k={k})", **metrics_after}
    ]).to_csv(OUT/"privacy_lab_metrics.csv", index=False)
    packages={}
    for package in ["numpy", "pandas", "scipy", "scikit-learn", "matplotlib"]:
        try:
            packages[package]=version(package)
        except PackageNotFoundError:
            packages[package]="not-installed"
    manifest={"timestamp_utc":datetime.now(timezone.utc).isoformat(), "python":platform.python_version(),
              "seed":seed, "dataset_size":n, "method":"generalization+k-suppression",
              "parameters":{"k":k,"l":l,"categorical_t":t},
              "model_configuration":"none in privacy-only runner",
              "metric_definitions":{"k":"minimum released equivalence-class size",
                                    "l":"minimum distinct sensitive values per group",
                                    "t":"categorical total-variation distance to released global distribution"},
              "dataset_provenance":"generated synthetic transactions; no external/provider records",
              "output_dir":str(OUT.resolve()),
              "output_files":list(output_files),
              "packages":packages,"quality":quality,"status":"completed"}
    (OUT/"experiment_manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    diag=privacy_diagnostics(anon, quasi, categorical_t=t, l_threshold=l)
    diag["l_satisfied"]=diag["distinct_l"] >= l
    pd.DataFrame([diag]).to_csv(OUT/"privacy_diagnostics.csv", index=False)
    return metrics_before, metrics_after

def create_template(path):
    rows=[]
    for app in APPS:
        for dim in DIMENSIONS:
            rows.append({"app":app,"dimension":dim,"claim":"",
                         "source_title":"","source_url":"","access_date":"",
                         "source_type":"","evidence_note":"","evidence_strength":"",
                         "reviewer":"","review_status":"unreviewed","score_rationale":"",
                         "raw_score":"",
                         "evidence_strength":"","source_type":"","source_url":"",
                         "access_date":"","notes":""})
    if not Path(path).exists():
        pd.DataFrame(rows).to_csv(path,index=False)

def export_report(metrics, before, after):
    OUT.mkdir(exist_ok=True)
    metrics.to_csv(OUT/"cpaf_app_comparison.csv", index=False)
    metrics.to_json(OUT/"cpaf_app_comparison.json", orient="records", indent=2)
    compute_weight_sensitivity(metrics).to_csv(OUT/"cpaf_weight_sensitivity.csv", index=False)
    scored = metrics.set_index("App")[DIMENSIONS]
    ax = scored.T.plot(kind="bar", figsize=(12,6))
    ax.set_ylabel("Evidence-adjusted score (1–5)")
    ax.set_title("CPAF 2.0: Dimension-level comparison (fill with audited evidence)")
    ax.set_ylim(1,5); plt.xticks(rotation=25, ha="right"); plt.tight_layout()
    plt.savefig(OUT/"dimension_scores.png", dpi=160); plt.close()
    fig, ax = plt.subplots(figsize=(8,4))
    labels=["Generalisation","Generalisation + k-suppression"]
    vals=[before["records_retained_pct"],after["records_retained_pct"]]
    ax.bar(labels, vals); ax.set_ylabel("Records retained (%)"); ax.set_ylim(0,105)
    ax.set_title("Synthetic privacy utility trade-off")
    plt.tight_layout(); plt.savefig(OUT/"privacy_utility_tradeoff.png",dpi=160); plt.close()

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument("--n",type=int,default=50000,help="number of synthetic records")
    parser.add_argument("--k",type=int,default=5,help="minimum equivalence-class size")
    parser.add_argument("--seed",type=int,default=42)
    parser.add_argument("--template-only",action="store_true")
    parser.add_argument("--no-ml",action="store_true",help="skip the model-training / ML privacy lab")
    parser.add_argument("--ml-only",action="store_true",help="run only the model-training / ML privacy lab")
    parser.add_argument("--l",type=int,default=2,help="distinct l-diversity diagnostic threshold")
    parser.add_argument("--t",type=float,default=.2,help="categorical-TV t-closeness diagnostic threshold")
    parser.add_argument("--sweep",action="store_true",help="run the reproducible k/l/t/generalization sweep")
    parser.add_argument("--plot-sweep-only",action="store_true",help="rebuild Pareto CSV/JSON/PNG from saved privacy_sweep.csv")
    parser.add_argument("--sweep-n",type=int,default=5000,help="synthetic rows per sweep seed")
    parser.add_argument("--sweep-k",type=int,nargs="+",default=[1,5,10])
    parser.add_argument("--sweep-l",type=int,nargs="+",default=[2,3])
    parser.add_argument("--sweep-t",type=float,nargs="+",default=[.1,.2])
    parser.add_argument("--sweep-levels",type=int,nargs="+",default=[1,2])
    parser.add_argument("--sweep-seeds",type=int,nargs="+",default=None)
    parser.add_argument("--repeated-ml",action="store_true",help="run repeated stratified logistic utility and synthetic age-group audit")
    parser.add_argument("--repeats",type=int,default=3,help="number of stratified train/test repeats")
    parser.add_argument("--attack-audit",action="store_true",help="run disjoint shadow-model MIA and synthetic disclosure proxies")
    parser.add_argument("--output-dir",default="cpaf_outputs",help="directory for this run's outputs")
    parser.add_argument("--config",default=None,help="JSON file supplying CLI defaults; explicit command-line flags override it")
    config_values={}
    config_args,_=parser.parse_known_args()
    if config_args.config:
        try:
            config_values=json.loads(Path(config_args.config).read_text(encoding="utf-8"))
        except (OSError,json.JSONDecodeError) as exc:
            parser.error(f"could not read config {config_args.config}: {exc}")
        valid_dests={action.dest for action in parser._actions}
        unknown=set(config_values)-valid_dests
        if unknown:
            parser.error(f"unknown config keys: {sorted(unknown)}")
        parser.set_defaults(**config_values)
    args=parser.parse_args()
    global OUT
    OUT=Path(args.output_dir)
    if args.plot_sweep_only:
        OUT.mkdir(parents=True,exist_ok=True)
    else:
        try:
            require_fresh_output_dir(OUT, allow_existing=("evidence_register_template.csv",))
        except FileExistsError as exc:
            parser.error(str(exc))
    def annotate_manifests():
        for manifest_path in OUT.glob("*manifest.json"):
            manifest_data=json.loads(manifest_path.read_text(encoding="utf-8"))
            manifest_data["configuration_file"]=args.config
            manifest_data["effective_cli_configuration"]={
                "n":args.n,"k":args.k,"seed":args.seed,"l":args.l,"t":args.t,
                "sweep_n":args.sweep_n,"sweep_k":args.sweep_k,"sweep_l":args.sweep_l,
                "sweep_t":args.sweep_t,"sweep_levels":args.sweep_levels,
                "sweep_seeds":args.sweep_seeds,"repeats":args.repeats,
                "output_dir":str(OUT)}
            if config_values:
                manifest_data["configuration_values"]=config_values
            manifest_path.write_text(json.dumps(manifest_data,indent=2),encoding="utf-8")
    template=OUT/"evidence_register_template.csv"
    create_template(template)
    if args.template_only:
        print(f"Created {template}. Fill it with documented evidence, then rerun.")
        return
    if args.sweep:
        seeds=args.sweep_seeds if args.sweep_seeds is not None else [args.seed]
        result,frontier=run_privacy_sweep(
            n=args.sweep_n,seeds=seeds,k_values=args.sweep_k,l_values=args.sweep_l,
            t_values=args.sweep_t,hierarchy_levels=args.sweep_levels,out_dir=OUT)
        annotate_manifests()
        print(f"Completed {len(result)} configurations; Pareto set has {len(frontier)} rows.")
        print(f"Sweep CSV, JSON, manifest and plot saved in: {OUT.resolve()}")
        return
    if args.plot_sweep_only:
        frontier=regenerate_sweep_outputs(OUT)
        print(f"Rebuilt Pareto outputs from saved CSV; {len(frontier)} configurations are non-dominated.")
        return
    if args.repeated_ml:
        runs,summary=run_repeated_utility(n=args.n,seed=args.seed,repeats=args.repeats,
                                          k=args.k,output_dir=OUT)
        annotate_manifests()
        print(summary.to_string(index=False))
        print(f"Repeated utility, fairness, distribution drift and manifest saved in: {OUT.resolve()}")
        return
    if args.attack_audit:
        result,proxies=run_shadow_mia(n=args.n,seed=args.seed,k=args.k,output_dir=OUT)
        annotate_manifests()
        print(result.to_string(index=False))
        print(json.dumps(proxies,indent=2))
        print(f"Shadow MIA and synthetic disclosure proxies saved in: {OUT.resolve()}")
        return
    if args.ml_only:
        from cpaf_ml import run_ml_lab
        run_ml_lab(args.n,args.k,args.seed,output_dir=OUT)
        annotate_manifests()
        print(f"Outputs saved in: {OUT.resolve()}")
        return
    before,after=run_privacy_lab(args.n,args.k,args.seed,args.l,args.t)
    annotate_manifests()
    evidence=pd.read_csv(template)
    # Empty template intentionally produces no app scores. This prevents invented findings.
    if evidence["raw_score"].notna().any():
        result=compute_app_metrics(evidence)
        export_report(result,before,after)
        print(result.to_string(index=False))
    else:
        print("Evidence template created but not scored. Add documented scores and rerun to calculate app CPI.")
    print("Synthetic privacy lab metrics:")
    print(pd.read_csv(OUT/"privacy_lab_metrics.csv").to_string(index=False))
    print(f"Dataset validation and privacy diagnostics saved under {OUT.resolve()}")
    if not args.no_ml:
        from cpaf_ml import run_ml_lab   # Layer 6: model training + attack + DP experiments
        run_ml_lab(args.n,args.k,args.seed,output_dir=OUT)
        annotate_manifests()
    print(f"Outputs saved in: {OUT.resolve()}")

if __name__=="__main__":
    main()
